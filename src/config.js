// --- 판 높이 ---
//
// z 는 화면에서 수직으로만 움직인다. 투영식을 풀면 (x, y, z) 는 바닥의
// (x−z, y−z) 칸 자리에 나타나는데, 이 이동은 sx 를 조금도 바꾸지 않는다.
// 따라서 착시로 이을 수 있는 판은 애초에 화면상 같은 세로줄(또는 한 칸 옆)에
// 있는 것뿐이고, 높이 조절은 그 줄 안에서 위아래를 맞추는 일이다.
//
// 상한 8 = 바닥의 절반. 대각으로 8칸 떨어진 판까지 이을 수 있다는 뜻이다.
// 무제한으로 두면 같은 세로줄 위의 어떤 판이든 맞출 수 있어 퍼즐이 헐거워지고,
// 4 로 조이면 이을 수 있는 조합이 드물어 착시가 좀처럼 성립하지 않는다.
//
// 잉크를 쓰지 않는다. "그리는 것은 비싸고 착시는 공짜"가 이 게임의 뿌리인데
// 높이는 착시를 만드는 바로 그 수단이다. 여기에 값을 매기면 잉크 경제 전체가
// 무너진다. 대신 상한 자체가 AI 디렉터의 세 번째 손잡이가 된다
// (잉크 배급량, 환급률에 이어). 층마다 상한을 조이면 착시 가능 조합이 줄어든다.
//
// 하한은 0. 음수 z 는 판을 격자선 아래로 내려보내, 두께를 위로 세워 고쳤던
// "바닥에 파묻힘"을 그대로 되살린다. 청사진 바닥은 부지이지 수면이 아니다.
//
// Z_MIN 은 상수로 남고 Z_MAX 는 층 파라미터의 기본값이 됐다. 하한이 0 인 것은
// 계산의 결론이라 층마다 달라질 여지가 없지만, 상한은 디렉터가 조이는 손잡이다.
// 실제로 게임이 읽는 것은 stage.zMax 다 (src/stage.js).
export const Z_MIN = 0;
export const Z_MAX = 8;

// --- 잉크 ---
//
// 그리는 데 잉크가 들고, 잉크는 유한하며, 착시는 공짜다.
// 이 세 줄이 게임의 나머지 규칙을 전부 파생시킨다. 다리는 여전히 그릴 수
// 있지만 비싸지고, 잉크가 조일수록 착시는 선택이 아니라 실력이 된다.
//
// 소모 2 / 환급 1 로 두어 절반 환급이 정수로 떨어지게 했다. 환급을 0.5 로
// 두면 반올림 방향에 따라 한 칸을 그렸다 지우는 것만으로 잉크가 늘어나는
// 구멍이 생긴다. 부동소수점을 아예 들이지 않는 편이 안전하다.
//
// 전액 환급으로 두지 않은 이유: 지우기가 완전히 공짜면 잉크는 "총량 제약"이
// 아니라 "한 번에 깔 수 있는 양"으로 축소된다. 그리는 총량이 무제한이 되면
// 다리를 그리는 값이 사실상 0 이 되어 착시를 쓸 이유가 사라진다.
//
// 다만 환급률로 막을 수 없는 것이 하나 있다. 앞에 그리고 뒤를 지우며 전진하는
// 징검다리 이동은 칸당 실질 비용이 (INK_COST - INK_REFUND) 로 떨어지므로,
// 환급이 0 보다 크면 언제나 길게 그리는 것보다 싸다. 현재 값에서 실측하면
// 직접 60칸 대 징검다리 110칸으로 1.8배 유리하다.
// 이것은 4단계에서 "캐릭터가 밟은 판은 환급하지 않는다" 로 막는다. 실험은
// 여전히 공짜이고 회수만 비싸진다. 캐릭터가 없는 지금은 구현할 수 없다.
//
// INK_REFUND 는 AI 디렉터의 두 번째 손잡이라 층 파라미터의 기본값이 됐다.
// 게임이 실제로 읽는 것은 stage.refund 다. INK_COST 는 상수로 남는다 —
// 소모 2 / 환급 1 의 정수 관계가 여기서 나오므로 층마다 흔들면
// 반올림 구멍이 되살아난다.
export const INK_COST = 2;
export const INK_REFUND = 1;

// 캐릭터가 밟은 칸은 환급하지 않는다.
//
// 2단계에서 실측으로 드러난 구멍을 막는다. 앞에 그리고 뒤를 지우며 전진하면
// 칸당 실질 비용이 (INK_COST − INK_REFUND) 로 떨어져, 직접 60칸 대 징검다리
// 110칸으로 1.8배 유리했다.
//
// 이 값이 0 이어야만 하는 것은 취향이 아니라 계산이다. N칸을 건널 때
//   직접 그리기  2N
//   징검다리     2N − R(N−k)      R = 밟은 칸 환급률
// 이므로 징검다리가 더 싸지 않으려면 R(N−k) ≤ 0, 즉 R ≤ 0 이다.
// 환급이 조금이라도 남으면 언제나 유리하다. 환급률을 낮추는 것으로는 막히지
// 않고 조건을 밟았는가/아닌가로 갈라야 한다는 뜻이다.
//
// 밟지 않은 칸은 INK_REFUND 를 그대로 받는다. 잘못 그린 다리를 걷지 않고
// 지우면 전액이 돌아오므로 설계 실험은 여전히 공짜이고, 실제로 지나간
// 경로만 매몰 비용이 된다.
export const INK_REFUND_STEPPED = 0;

// 배급량 기본값. 1층이 쓰는 값이자, 디렉터가 생략한 층을 채우는 값이다.
// 게임이 실제로 읽는 것은 stage.inkMax 다.
//
// 60칸 = 16×16 바닥(256칸)의 약 23%. 판 크기에 연동시키지 않고 절대값으로
// 두는 이유는, 배급량이 판 크기가 아니라 목표까지의 거리에 달려 있기 때문이다.
// 비례식으로 묶으면 디렉터가 둘을 독립적으로 조절할 수 없다.
export const INK_MAX = 120;   // = 60칸

