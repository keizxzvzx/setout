// 경고가 아니기 때문이다. 0.25 로 올리면 확정 잉크와 헷갈리고, 그러면 게이지가
// "지금 쓸 수 있는 양" 이라는 뜻이 흐려진다. 걸어서 짧아지는 것은 옅어도 보인다 —
